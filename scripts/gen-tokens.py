#!/usr/bin/env python3
"""Generate SimplifyKit's Swift design tokens from design/tokens.json.

    python3 scripts/gen-tokens.py

Writes Packages/SimplifyKit/Sources/SimplifyKit/Design/Tokens.generated.swift.
Run it again whenever design/tokens.json changes; never edit the output by hand.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "design" / "tokens.json"
OUT = ROOT / "Packages/SimplifyKit/Sources/SimplifyKit/Design/Tokens.generated.swift"


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(p.capitalize() for p in rest)


def hex_literal(value):
    return "0x" + value.lstrip("#").lower()


def px(value):
    return value.removesuffix("px")


tokens = json.loads(SRC.read_text())
colors = {t["name"]: t for t in tokens["color"]["tokens"]}
palette = [n.removesuffix("-ink") for n in colors if n.endswith("-ink") and n != "on-ink"]


def color_expr(name):
    value = colors[name]["value"]
    if isinstance(value, str) and value.startswith("{"):
        return f"Tokens.{camel(value[1:-1])}"
    if isinstance(value, str):
        return f"Color(light: {hex_literal(value)}, dark: {hex_literal(value)})"
    return f"Color(light: {hex_literal(value['light'])}, dark: {hex_literal(value['dark'])})"


# Names SwiftUI already uses as ShapeStyle shortcuts; use Tokens.<name> for these instead.
SWIFTUI_STYLES = {"link"}
base = [n for n in colors
        if not any(n.startswith(p + "-") for p in palette) and n not in SWIFTUI_STYLES]
lines = [
    "// Generated by scripts/gen-tokens.py from design/tokens.json. Do not edit.",
    "",
    "import SwiftUI",
    "",
    "/// Colour values for both themes (white wall = light, black wall = dark).",
    "public enum Tokens {",
]
for n in colors:
    lines.append(f"    /// {colors[n]['usage']}")
    lines.append(f"    public static let {camel(n)} = {color_expr(n)}")
shadow = next(t for t in tokens["shadow"]["tokens"] if t["name"] == "shadow-drawn")["value"]
shadow_hex = {k: re.search(r"#[0-9a-fA-F]{6}", v).group(0) for k, v in shadow.items()}
lines += [
    "    /// The flat cartoon shadow under drawn objects.",
    f"    public static let shadowDrawn = Color(light: {hex_literal(shadow_hex['light'])}, dark: {hex_literal(shadow_hex['dark'])})",
    "}",
    "",
    "public extension ShapeStyle where Self == Color {",
]
for n in base:
    lines.append(f"    static var {camel(n)}: Color {{ Tokens.{camel(n)} }}")
lines += [
    "}",
    "",
    "/// The nine colours people put on their own content: calendars, memo text and highlights, ToDo labels.",
    "public enum Palette: String, CaseIterable, Codable, Sendable {",
    "    case " + ", ".join(palette),
    "",
    "    /// For text and marks; 4.5:1 on paper and on its own tint.",
    "    public var ink: Color {",
    "        switch self {",
]
lines += [f"        case .{p}: Tokens.{camel(p + '-ink')}" for p in palette]
lines += ["        }", "    }", "", "    /// For highlighter and all-day band backgrounds.", "    public var tint: Color {", "        switch self {"]
lines += [f"        case .{p}: Tokens.{camel(p + '-tint')}" for p in palette]
lines += ["        }", "    }", "", "    public var name: String {", "        switch self {"]
for p in palette:
    korean = re.search(r"·\s*(\S+?):", colors[p + "-ink"]["usage"]).group(1)
    lines.append(f'        case .{p}: "{korean}"')
lines += ["        }", "    }", "}", "", "public enum Metrics {"]
for fam in ("line", "spacing", "radius"):
    for t in tokens[fam]["tokens"]:
        lines.append(f"    /// {t['usage']}")
        lines.append(f"    public static let {camel(t['name'])}: CGFloat = {px(t['value'])}")
lines += ["}", ""]

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines))
print(f"wrote {OUT.relative_to(ROOT)}")
